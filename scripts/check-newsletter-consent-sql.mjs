import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const {PGlite}=await import(process.argv[2]||'@electric-sql/pglite');const db=new PGlite();let count=0;
const check=(ok,label)=>{assert.ok(ok,label);count++;console.log('OK '+label);};
const denied=async sql=>{try{await db.exec(sql);return false;}catch{return true;}};
const query=(sql,params)=>db.query(sql,params);
const choose=(email,enabled)=>query("select public.cm_newsletter_choose($1,$2,'v1','Consent snapshot','profile') as revision",[email,enabled]);
try{
await db.exec('CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;');
await db.exec(await readFile(new URL('../supabase/migrations/20260926_newsletter_consent.sql',import.meta.url),'utf8'));
check(true,'Migration applies to empty PostgreSQL');
for(const role of ['anon','authenticated']){
 await db.exec(`SET ROLE ${role}`);
 for(const table of ['cm_newsletter_preferences','cm_newsletter_consent_events','cm_newsletter_confirmations'])check(await denied(`select * from public.${table}`),`${role} cannot read ${table}`);
 check(await denied("select public.cm_newsletter_choose('rider@example.com',true,'v1','text','profile')"),`${role} cannot manufacture consent`);
 check(await denied("select public.cm_newsletter_confirm(repeat('a',64))"),`${role} cannot confirm via public SQL`);
 await db.exec('RESET ROLE');
}
await db.exec('SET ROLE service_role');
await choose('rider@example.com',true);
let events=(await query('select * from public.cm_newsletter_consent_events')).rows;
check(events.length===1&&events[0].consent_text==='Consent snapshot','Choice and exact text recorded together');
check(await denied("select public.cm_newsletter_choose('rider@example.com',false,'v1','text','bad-source')"),'Invalid proof rejects entire transaction');
check((await query('select enabled from public.cm_newsletter_preferences')).rows[0].enabled===true,'No preference change without proof');
const lease='00000000-0000-4000-8000-000000000001';
const job=(await query('select * from public.cm_newsletter_claim($1,$2)',['rider@example.com',lease])).rows[0];
check(!!job,'Worker acquires pending job');
check((await query('select * from public.cm_newsletter_claim($1,$2)',['rider@example.com',lease])).rows.length===0,'No overlapping worker during lease');
await choose('rider@example.com',false);
await query('select public.cm_newsletter_finish($1,$2,$3,null)',['rider@example.com',job.revision,lease]);
let pref=(await query('select * from public.cm_newsletter_preferences')).rows[0];
check(pref.enabled===false&&pref.sync_pending,'Old acknowledgement cannot erase later withdrawal');
const fresh=(await query('select * from public.cm_newsletter_claim($1,$2)',['rider@example.com',lease])).rows[0];
await query('select public.cm_newsletter_finish($1,$2,$3,null)',['rider@example.com',fresh.revision,lease]);
check((await query('select sync_pending from public.cm_newsletter_preferences')).rows[0].sync_pending===false,'Current revision acknowledged');
const request=()=>query("select public.cm_newsletter_request('new@example.com',repeat('b',64),'v1','Checkbox text') as allowed");
check((await request()).rows[0].allowed,'Confirmation request stored separately');
check(!(await request()).rows[0].allowed,'Per-address email cooldown');
check((await query("select count(*)::int as n from public.cm_newsletter_preferences where email='new@example.com'")).rows[0].n===0,'Request alone never subscribes');
check((await query("select public.cm_newsletter_confirm(repeat('c',64)) as email")).rows[0].email===null,'Unknown token rejected');
check((await query("select public.cm_newsletter_confirm(repeat('b',64)) as email")).rows[0].email==='new@example.com','Confirmation grants consent');
check((await query("select public.cm_newsletter_confirm(repeat('b',64)) as email")).rows[0].email===null,'Token cannot be replayed');
await query("select public.cm_newsletter_request('new@example.com',repeat('d',64),'v1','text')");
await choose('new@example.com',false);
check((await query("select public.cm_newsletter_confirm(repeat('d',64)) as email")).rows[0].email===null,'Withdrawal invalidates older confirmation links');
await query("select public.cm_newsletter_request('expired@example.com',repeat('e',64),'v1','text')");
await db.exec("update public.cm_newsletter_confirmations set expires_at=now()-interval '1 minute'");
check((await query("select public.cm_newsletter_confirm(repeat('e',64)) as email")).rows[0].email===null,'Expired token rejected');
await choose('new@example.com',true);
await db.exec("select public.cm_newsletter_provider_withdraw('new@example.com',now()-interval '1 day')");
check((await query("select enabled from public.cm_newsletter_preferences where email='new@example.com'")).rows[0].enabled,'Delayed webhook cannot override new consent');
await db.exec("select public.cm_newsletter_provider_withdraw('new@example.com',now())");
check(!(await query("select enabled from public.cm_newsletter_preferences where email='new@example.com'")).rows[0].enabled,'Current provider withdrawal is recorded');
await db.exec("select public.cm_newsletter_provider_withdraw('other-business@example.com',now())");
check((await query("select count(*)::int as n from public.cm_newsletter_preferences where email='other-business@example.com'")).rows[0].n===0,'Other MailerLite customers are ignored');
await db.exec("update public.cm_newsletter_preferences set enabled=false,sync_pending=false,updated_at=now()-interval '25 months' where email='rider@example.com'; select public.cm_newsletter_purge()");
check((await query("select count(*)::int as n from public.cm_newsletter_consent_events where email='rider@example.com'")).rows[0].n===0,'Expired withdrawn preference and proof are purged');
check((await query('select count(*)::int as n from public.cm_newsletter_confirmations')).rows[0].n===0,'Expired pending addresses are purged');
console.log(`${count} SQL checks passed; no remote database used.`);
}finally{await db.close();}
