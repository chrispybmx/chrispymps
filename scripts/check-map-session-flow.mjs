import {createRequire} from 'node:module';
import {randomUUID} from 'node:crypto';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const browsers=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const engine=process.env.BROWSER_ENGINE||'chromium';
const origin=process.env.PREVIEW_ORIGIN||'http://127.0.0.1:3200';
if(!['localhost','127.0.0.1'].includes(new URL(origin).hostname))throw new Error('Local preview only');
const headers={Authorization:'Bearer local-rider-session-preview','Content-Type':'application/json'};
async function api(body){const r=await fetch(`${origin}/api/rider-sessions-preview`,{headers,...(body?{method:'POST',body:JSON.stringify(body)}:{})});const j=await r.json();assert.equal(r.status,200);return j.data;}
const command=command=>api({requestId:randomUUID(),command});
assert.equal((await api()).sessions.length,0,'Use an empty local demo database');
const browser=await browsers[engine].launch({headless:true,...(engine==='chromium'&&process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
const ids=[];
try{
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{
  localStorage.setItem('cmaps_cookie_notice','1');localStorage.setItem('cmaps_onboarding_v2','1');
  window.__gpsCalls=0;
  navigator.geolocation.getCurrentPosition=(_ok,fail)=>{window.__gpsCalls++;fail?.({code:1,message:'Test denied'});};
 });
 await page.goto(`${origin}/map`,{waitUntil:'domcontentloaded'});
 const plus=page.getByRole('button',{name:'Spot e sessioni',exact:true});
 await plus.tap();await page.getByRole('dialog',{name:'Cosa vuoi fare?',exact:true}).waitFor();
 await page.waitForFunction(()=>{const r=document.querySelector('.mbn-actions')?.getBoundingClientRect();return r&&Math.abs(r.bottom-innerHeight)<2;});
 await page.waitForFunction(()=>[...document.querySelectorAll('.leaflet-tile')].some(img=>img.complete&&img.naturalWidth>0));
 await page.screenshot({path:`/private/tmp/chrispy-actions-sheet-${engine}.png`});
 await page.getByRole('button',{name:'Vai in sessione',exact:true}).tap();
 const panel=page.getByRole('region',{name:'Inizia una sessione',exact:true});
 await panel.getByRole('searchbox').fill('Jungle');
 assert.equal(await panel.getByRole('radio',{name:'Solo io',exact:true}).isChecked(),true);
 await panel.getByRole('button',{name:/Jungle.*Inizia/}).tap();
 await panel.getByLabel('Durata della sessione',{exact:true}).waitFor();
 let state=await api();const active=state.sessions.find(s=>s.status==='active');assert.ok(active);ids.push(active.id);
 assert.equal(active.visibility,'private');assert.equal(state.sessions.length,1);
 const timer=panel.getByLabel('Durata della sessione',{exact:true});const before=await timer.innerText();
 await page.waitForFunction(value=>document.querySelector('[aria-label="Durata della sessione"]')?.textContent!==value,before,{timeout:8000});
 await page.screenshot({path:`/private/tmp/chrispy-session-timer-${engine}.png`});
 const gpsBefore=await page.evaluate(()=>window.__gpsCalls);
 await panel.getByRole('button',{name:'Torna alla mappa',exact:true}).tap();
 await plus.tap();await page.getByRole('button',{name:'Vai in sessione',exact:true}).tap();
 await timer.waitFor();assert.equal(await page.evaluate(()=>window.__gpsCalls),gpsBefore,'Reopen timer without requesting GPS');
 await page.goto(`${origin}/map?session=1`,{waitUntil:'domcontentloaded'});await timer.waitFor();
 assert.equal((await api()).sessions.length,1,'Refresh must not duplicate a session');
 await page.goto(`${origin}/u/rider_demo`,{waitUntil:'domcontentloaded'});
 await page.getByRole('link',{name:'Sessione in corso',exact:true}).waitFor();
 assert.equal((await page.locator('body').innerText()).includes(active.spotName),false);
 assert.equal(await page.getByRole('group',{name:/Com’è andata/}).count(),0);
 assert.equal(await page.getByRole('complementary',{name:'Sessione in corso'}).count(),0);
 await page.getByRole('link',{name:'Sessione in corso',exact:true}).click();
 await page.getByRole('region',{name:'Le tue sessioni'}).getByRole('button',{name:'Termina sessione',exact:true}).click();
 await page.getByRole('button',{name:'Bella sessione',exact:true}).click();
 state=await api();assert.equal(state.confirmedCount,1);assert.equal(state.sessions[0].mood,'happy');
 await page.goto(`${origin}/u/rider_demo`,{waitUntil:'domcontentloaded'});
 await page.getByRole('link',{name:'Gestisci sessioni',exact:true}).waitFor();
 assert.equal((await page.locator('body').innerText()).includes(active.spotName),false);
 assert.equal(await page.getByRole('button',{name:'Bella sessione',exact:true}).count(),0);
 await page.screenshot({path:`/private/tmp/chrispy-clean-profile-${engine}.png`});
 state=await command({action:'start',spotId:active.spotId,visibility:'private'});
 const next=state.sessions.find(s=>s.status==='active');ids.push(next.id);
 await api({demoExpire:true});await page.reload();
 await page.getByRole('link',{name:'1 sessione da confermare',exact:true}).waitFor();
 assert.equal((await api()).confirmedCount,1);
 assert.equal((await page.locator('body').innerText()).includes(active.spotName),false);
 await page.goto(`${origin}/map?session=1`,{waitUntil:'domcontentloaded'});
 await panel.getByRole('heading',{name:'Fine da confermare',exact:true}).waitFor();
 assert.equal(await panel.getByLabel('Durata della sessione',{exact:true}).count(),0);
 assert.equal(await page.evaluate(()=>window.__gpsCalls),0,'Expired session must not request GPS again');
 assert.deepEqual(errors,[]);
 console.log(`PASS ${engine}: sheet > nearest/manual choice > timer, refresh, reopen without GPS, stop, clean owner profile, private management, two-hour confirmation`);
}finally{
 await browser.close();for(const id of ids)await command({action:'delete',id});
}
