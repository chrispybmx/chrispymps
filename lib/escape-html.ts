/* Per testo scritto dagli utenti che finisce in stringhe HTML: tooltip e popup
   di Leaflet inseriscono il contenuto come HTML, non come testo. */
export function escapeHtml(value: string | null | undefined): string {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
